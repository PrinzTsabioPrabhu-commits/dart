void main() {
  // Menghitung lap balapan dari lap 1 sampai 5
  for (int lap = 1; lap <= 5; lap++) {
    print('Melibas Lap ke-$lap di sirkuit');
  }
}

// Output:
// Melibas Lap ke-1 di sirkuit
// Melibas Lap ke-2 di sirkuit
// Melibas Lap ke-3 di sirkuit
// Melibas Lap ke-4 di sirkuit
// Melibas Lap ke-5 di sirkuit